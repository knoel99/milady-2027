#!/usr/bin/env bash
# Generate infra/docker/.env from infra/docker/.env.example, with random passwords.
#
# Usage: infra/deploy/gen_env.sh [--gpu|--cpu] [--owner USER]
#   --gpu / --cpu    force the compute container (worker-gpu / worker); default: nvidia-smi detection
#   --owner U        user owning the repository (container UID/GID); default: $SUDO_USER
#                    or the current user
#
# Idempotent: if .env already exists, it is NEVER overwritten (the passwords are already written
# into the PostgreSQL and MinIO volumes); only the missing variables are added.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
EXAMPLE="${REPO_ROOT}/infra/docker/.env.example"
TARGET="${REPO_ROOT}/infra/docker/.env"

worker=""
owner="${SUDO_USER:-$(id -un)}"
while [[ $# -gt 0 ]]; do
    case "$1" in
        --gpu) worker="worker-gpu" ;;
        --cpu) worker="worker" ;;
        --owner) owner="$2"; shift ;;
        -h|--help) sed -n '2,11p' "$0"; exit 0 ;;
        *) echo "Unknown option: $1" >&2; exit 2 ;;
    esac
    shift
done

# GPU detection if not forced.
if [[ -z "${worker}" ]]; then
    if command -v nvidia-smi >/dev/null 2>&1 && nvidia-smi -L >/dev/null 2>&1; then
        worker="worker-gpu"
    else
        worker="worker"
    fi
fi

# Random alphanumeric secret (no special characters: it is inserted into URLs).
rand() {
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -hex "${1:-24}"
    else
        head -c "${1:-24}" /dev/urandom | od -An -tx1 | tr -d ' \n'
    fi
}

uid="$(id -u "${owner}")"
gid="$(id -g "${owner}")"
if [[ "${uid}" -eq 0 ]]; then
    # Containers run without root: repository owned by root → UID/GID 1000 in the container
    # (bootstrap_vm.sh then gives data/ to UID 1000).
    echo "Owner is root: containers use UID/GID 1000 (cloning the repository as a normal user is preferable)."
    uid=1000
    gid=1000
fi
host="$(hostname -s 2>/dev/null || hostname)"

if [[ -f "${TARGET}" ]]; then
    echo ".env already exists (${TARGET}): kept as is."
    # Only fills in the new variables of the template (repository update).
    added=0
    while IFS= read -r line; do
        [[ "${line}" =~ ^([A-Z_][A-Z0-9_]*)= ]] || continue
        key="${BASH_REMATCH[1]}"
        if ! grep -q "^${key}=" "${TARGET}"; then
            value="${line#*=}"
            [[ "${value}" == "change-me" ]] && value="$(rand 24)"
            printf '%s=%s\n' "${key}" "${value}" >> "${TARGET}"
            echo "  variable added: ${key}"
            added=$((added + 1))
        fi
    done < "${EXAMPLE}"
    [[ ${added} -eq 0 ]] || echo "  ${added} variable(s) added."
    exit 0
fi

umask 077
tmp="$(mktemp "${TARGET}.XXXXXX")"
trap 'rm -f "${tmp}"' EXIT
{
    echo "# Generated by infra/deploy/gen_env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) — DO NOT COMMIT."
    while IFS= read -r line; do
        if [[ "${line}" =~ ^([A-Z_][A-Z0-9_]*)=(.*)$ ]]; then
            key="${BASH_REMATCH[1]}"
            value="${BASH_REMATCH[2]}"
            case "${key}" in
                MILADY_WORKER) value="${worker}" ;;
                MILADY_UID) value="${uid}" ;;
                MILADY_GID) value="${gid}" ;;
                MILADY_HOST) value="${host}" ;;
            esac
            [[ "${value}" == "change-me" ]] && value="$(rand 24)"
            printf '%s=%s\n' "${key}" "${value}"
        else
            printf '%s\n' "${line}"
        fi
    done < "${EXAMPLE}"
} > "${tmp}"
mv "${tmp}" "${TARGET}"
trap - EXIT
chmod 600 "${TARGET}"
# The repository owner must be able to read .env (make without sudo).
if [[ "$(id -u)" -eq 0 && "${owner}" != "root" ]]; then
    chown "$(id -u "${owner}"):$(id -g "${owner}")" "${TARGET}"
fi
echo "Created: ${TARGET} (compute container: ${worker}, UID ${uid})."
