#!/usr/bin/env python3
"""Team cards of the home page, the table of the Teams page and the team links of the Site menu.

Every planned team is listed: the pilots (race/PILOT.md is the Claude pilot, race/PILOT-<TEAM>.md
the others) and the teams of race/config.toml [teams]. A team's links appear as soon as its
deliverables exist under site/teams/<team>/ (report/index.qmd, report/index.pdf, explorer/index.qmd,
diagrams/*.html); until then the card says "planned".

Writes:
  site/_team-cards.md        included by site/index.qmd
  site/teams/_team-table.md  included by site/teams/index.qmd
  site/assets/theme.js       the block between /* teams:begin */ and /* teams:end */

  python3 tools/teams_index.py           # write
  python3 tools/teams_index.py --check   # exit 1 if a file is out of date (CI)
"""
from __future__ import annotations

import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"

NAMES = {
    "claude": "Claude", "cursor": "Cursor", "openai": "OpenAI", "google": "Google",
    "xai": "xAI", "mistral": "Mistral", "zhipu": "Zhipu", "moonshot": "Moonshot",
    "deepseek": "DeepSeek", "alibaba": "Alibaba",
}
HARNESS = {"claude": "Claude Code cloud session", "cursor": "Cursor Cloud Agents"}


def teams() -> list[dict]:
    config = tomllib.loads((ROOT / "race/config.toml").read_text(encoding="utf-8"))
    providers = tomllib.loads((ROOT / "agents/providers.toml").read_text(encoding="utf-8"))
    pilots = []
    if (ROOT / "race/PILOT.md").exists():
        pilots.append("claude")
    for f in sorted((ROOT / "race").glob("PILOT-*.md")):
        m = re.fullmatch(r"PILOT-([A-Z0-9_]+)\.md", f.name)
        if m and m.group(1).lower() in providers and m.group(1).lower() not in pilots:
            pilots.append(m.group(1).lower())
    race = list(config.get("teams", {}))
    on_disk = sorted(p.name for p in (SITE / "teams").iterdir() if p.is_dir())
    order = pilots + [t for t in race if t not in pilots] + [t for t in on_disk if t not in pilots + race]
    out = []
    for t in order:
        d = SITE / "teams" / t
        best = next(iter(providers.get(t, {}).get("index", {})), None)  # first entry: the frontier model
        model = re.sub(r"\s*\(.*$|,.*$", "", best) if best else None
        out.append({
            "id": t,
            "name": NAMES.get(t, t.capitalize()),
            "kind": {(True, True): "Pilot team, also in the race", (True, False): "Pilot team",
                     (False, True): "Race team"}.get((t in pilots, t in race), "Team"),
            "harness": HARNESS.get(t),
            "model": model,
            "pilot": t in pilots,
            "report": (d / "report/index.qmd").exists(),
            "pdf": (d / "report/index.pdf").exists(),
            "explorer": (d / "explorer/index.qmd").exists(),
            "diagrams": sorted(p.name for p in (d / "diagrams").glob("*.html")) if d.is_dir() else [],
        })
    return out


def links(t: dict, prefix: str) -> list[str]:
    b = f"{prefix}{t['id']}/"
    out = []
    if t["report"]:
        out.append(f"[Report]({b}report/index.html)")
    if t["pdf"]:
        out.append(f'[PDF]({b}report/index.pdf){{download=""}}')
    if t["explorer"]:
        out.append(f"[Explorer]({b}explorer/index.html)")
    return out


def cards(ts: list[dict]) -> str:
    lines = ["<!-- Generated by tools/teams_index.py: do not edit. -->", "", "::: {.team-cards}"]
    for t in sorted(ts, key=lambda t: not t["report"]):  # published reports first
        done = t["report"]
        status = "Report published" if done else "In progress" if t["pilot"] else "Planned"
        lines += ["", f"::: {{.team-card{' .ready' if done else ''}}}",
                  f"[{t['name']}]{{.team-name}} [{status}]{{.team-status}}", ""]
        meta = t["kind"] + "".join(f" · {x}" for x in (t["harness"],) if x)
        if t["model"]:
            meta += f" · {t['model']}"
        lines.append(f"[{meta}]{{.team-meta}}")
        lines.append("")
        lk = links(t, "teams/")
        lines.append(" · ".join(lk) if lk else "[Report to come]{.team-none}")
        lines.append(":::")
    lines += ["", ":::", ""]
    return "\n".join(lines)


def table(ts: list[dict]) -> str:
    lines = ["<!-- Generated by tools/teams_index.py: do not edit. -->", "",
             "| Team | Status | HTML report | PDF | Explorer | Diagrams |", "|---|---|---|---|---|---|"]
    for t in ts:
        b = f"{t['id']}/"
        cell = lambda ok, md: md if ok else "—"
        diags = " · ".join(f"[{Path(x).stem.replace('-', ' ').capitalize()}]({b}diagrams/{x})"
                           for x in t["diagrams"]) or "—"
        lines.append(" | ".join([
            f"| **{t['name']}** ({t['kind'].lower()})",
            "report published" if t["report"] else "in progress" if t["pilot"] else "planned",
            cell(t["report"], f"[HTML report]({b}report/index.html)"),
            cell(t["pdf"], f'[Download the PDF]({b}report/index.pdf){{download=""}}'),
            cell(t["explorer"], f"[Explorer]({b}explorer/index.html)"),
            diags]) + " |")
    lines.append("")
    return "\n".join(lines)


def nav(ts: list[dict]) -> str:
    items = []
    for t in ts:
        if t["report"]:
            items.append([f"teams/{t['id']}/report/index.html", f"{t['name']} team: report (HTML)"])
        if t["pdf"]:
            items.append([f"teams/{t['id']}/report/index.pdf", f"{t['name']} team: report (PDF)", True])
        if t["explorer"]:
            items.append([f"teams/{t['id']}/explorer/index.html", f"{t['name']} team: explorer"])
    body = ",\n    ".join(json.dumps(i, ensure_ascii=False) for i in items)
    return f"/* teams:begin */\n  var TEAM_LINKS = [\n    {body}\n  ];\n  /* teams:end */"


def main() -> int:
    check = sys.argv[1:] == ["--check"]
    ts = teams()
    theme = SITE / "assets/theme.js"
    js = theme.read_text(encoding="utf-8")
    new_js, n = re.subn(r"/\* teams:begin \*/.*?/\* teams:end \*/", lambda _: nav(ts), js, flags=re.DOTALL)
    if n != 1:
        print("theme.js: teams:begin / teams:end block not found")
        return 1
    targets = {SITE / "_team-cards.md": cards(ts), SITE / "teams/_team-table.md": table(ts), theme: new_js}
    stale = [p for p, txt in targets.items() if not p.exists() or p.read_text(encoding="utf-8") != txt]
    if check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)} (run python3 tools/teams_index.py)")
        return 1 if stale else 0
    for p in stale:
        p.write_text(targets[p], encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
