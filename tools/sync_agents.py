#!/usr/bin/env python3
"""Generate tool-specific sub-agent files from the provider-neutral roles.

Reads agents/roles/*.md and agents/providers.toml, and writes one file per role
for each provider section whose format is supported (today: claude-code, cursor).

    python3 tools/sync_agents.py           # regenerate
    python3 tools/sync_agents.py --check   # exit 1 if a generated file is out of date
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROLES = ROOT / "agents" / "roles"
PROVIDERS = ROOT / "agents" / "providers.toml"
REQUIRED = ("name", "description", "tier", "reasoning", "read_only", "needs", "max_turns")
NEEDS = {"shell", "web"}


def parse_role(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        sys.exit(f"{path}: missing header")
    _, header, body = text.split("---\n", 2)
    meta: dict = {}
    for line in header.splitlines():
        if not line.strip():
            continue
        key, _, value = line.partition(":")
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            meta[key.strip()] = [v.strip() for v in value[1:-1].split(",") if v.strip()]
        elif value in ("true", "false"):
            meta[key.strip()] = value == "true"
        else:
            meta[key.strip()] = value
    missing = [k for k in REQUIRED if k not in meta]
    if missing:
        sys.exit(f"{path}: missing fields {missing}")
    if meta["name"] != path.stem:
        sys.exit(f"{path}: name {meta['name']!r} does not match the file name")
    unknown = set(meta["needs"]) - NEEDS
    if unknown:
        sys.exit(f"{path}: unknown needs {sorted(unknown)}")
    return meta, body


def render_claude(meta: dict, body: str, cfg: dict, role_path: Path) -> str:
    tools = list(cfg["tools"]["base"])
    for need in ("shell", "web"):
        if need in meta["needs"]:
            tools += cfg["tools"][need]
    if not meta["read_only"]:
        tools += cfg["tools"]["write"]
    lines = [
        "---",
        f"# Generated by tools/sync_agents.py from {role_path.relative_to(ROOT)}: do not edit.",
        f"name: {meta['name']}",
        f"description: {meta['description']}",
        f"tools: {', '.join(tools)}",
    ]
    if meta["read_only"]:
        lines.append(f"disallowedTools: {', '.join(cfg['tools']['write'])}")
    lines += [
        f"model: {cfg['tier'][meta['tier']]}",
        f"effort: {cfg['reasoning'][meta['reasoning']]}",
        f"maxTurns: {meta['max_turns']}",
        "---",
    ]
    return "\n".join(lines) + "\n" + body


def render_cursor(meta: dict, body: str, cfg: dict, role_path: Path) -> str:
    params = [f"effort={cfg['reasoning'][meta['reasoning']]}"]
    if cfg.get("fast"):
        params.append("fast=true")
    lines = [
        "---",
        f"# Generated by tools/sync_agents.py from {role_path.relative_to(ROOT)}: do not edit.",
        f"name: {meta['name']}",
        f"description: {meta['description']}",
        f"model: {cfg['tier'][meta['tier']]}[{','.join(params)}]",
        f"readonly: {'true' if meta['read_only'] else 'false'}",
        "---",
    ]
    return "\n".join(lines) + "\n" + body


RENDERERS = {"claude-code": render_claude, "cursor": render_cursor}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if a generated file is out of date")
    args = parser.parse_args()

    providers = tomllib.loads(PROVIDERS.read_text(encoding="utf-8"))
    roles = sorted(ROLES.glob("*.md"))
    stale = []
    for provider, cfg in providers.items():
        if cfg.get("format") == "none":
            continue  # catalogue only: no generator for this provider yet
        render = RENDERERS.get(cfg.get("format", ""))
        if render is None:
            print(f"skip {provider}: format {cfg.get('format')!r} not supported")
            continue
        out_dir = ROOT / cfg["output_dir"]
        expected = {}
        for role in roles:
            meta, body = parse_role(role)
            expected[out_dir / role.name] = render(meta, body, cfg, role)
        extra = [p for p in out_dir.glob("*.md") if p not in expected]
        for path, text in expected.items():
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != text:
                stale.append(path)
                if not args.check:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(text, encoding="utf-8")
        for path in extra:
            stale.append(path)
            if not args.check:
                path.unlink()
    for path in stale:
        verb = "out of date" if args.check else "updated"
        print(f"{verb}: {path.relative_to(ROOT)}")
    if args.check and stale:
        print("run: python3 tools/sync_agents.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
